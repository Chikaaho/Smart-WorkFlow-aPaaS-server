package com.sw.ck.bpm.api.result;

/**
 * 流程变更类操作的统一结果（跨模块 API 结果类型）。
 * <p>
 * 供原先返回 {@code void} 的命令方法表达"已执行"与"合法幂等/零变更"的区别：
 * 目标缺失或幂等重复是合法结果，必须以 present 值表达，不得伪装成 empty，
 * 也不得伪装成失败。真实错误（参数非法、状态冲突、基础设施失败）继续抛明确异常。
 * </p>
 */
public enum MutationOutcome {

    /** 本次调用产生了预期副作用（状态迁移、记录写入或实例变更已生效）。 */
    APPLIED,

    /**
     * 目标已处于期望状态，或本次调用没有可变更对象（幂等重复、无可关闭分支等），
     * 调用语义已满足且未产生第二次效果；不是失败。
     */
    ALREADY_APPLIED
}
